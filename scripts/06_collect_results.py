"""Collect the result tables produced by scripts 01-05 into results/RESULTS_SUMMARY.md.

Only copies numbers from the CSV/JSON outputs (no interpretation), so every value
in the report can be traced back to a file in results/.
"""
import sys, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import pandas as pd
from pathsnap import config as C

R = C.RESULTS_DIR
out = ["# PathSnap – results summary (auto-generated by scripts/06_collect_results.py)\n"]


def section(title, path, cols=None, fmt=4, index=False):
    p = R / path
    if not p.exists():
        out.append(f"\n## {title}\n\n_missing: {path}_\n"); return
    df = pd.read_csv(p, index_col=0 if index else None)
    if cols:
        df = df[[c for c in cols if c in df.columns]]
    out.append(f"\n## {title}\n\nSource: `results/{path}`\n\n" + df.round(fmt).to_markdown(index=index) + "\n")


section("Dataset summary per partition", "eda/partition_summary.csv", index=True, fmt=3)
section("Model comparison (CV = 5-fold GroupKFold on train; test = 10 student-test trips)",
        "models/model_comparison.csv",
        ["model", "family", "cv_f1_macro_mean", "cv_f1_macro_std", "cv_top1_mean", "cv_top1_std", "cv_log_loss_mean",
         "test_top1", "test_f1_macro", "test_precision_macro", "test_recall_macro", "test_log_loss",
         "test_continuity", "train_time_s", "infer_time_s"])
sel = R / "models" / "selection.json"
if sel.exists():
    out.append("\nSelection: `" + sel.read_text().replace("\n", " ") + "`\n")
section("Bayesian optimisation: tuned vs untuned", "bayes_opt/tuned_vs_untuned.csv")
bp = R / "bayes_opt" / "best_params.json"
if bp.exists():
    out.append("\n```json\n" + bp.read_text() + "\n```\n")
section("HMM decoder grid search (train, out-of-fold probabilities)", "hmm/decoder_grid_search_train_oof.csv")
section("Classifier-only vs classifier+HMM (student-test, mean over trips)", "hmm/student_test_clf_vs_hmm_summary.csv", index=True)
section("Per-trip student-test comparison", "hmm/student_test_clf_vs_hmm_per_trip.csv",
        ["trip", "method", "n_points", "top1_accuracy", "route_continuity", "route_precision", "route_recall", "route_f1",
         "hmm_breaks"])
(R / "RESULTS_SUMMARY.md").write_text("\n".join(out))
print("wrote", R / "RESULTS_SUMMARY.md")
